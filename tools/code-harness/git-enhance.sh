# Configures the current checkout with the enhancements available for its
# repo, and removes enhancements that no longer apply. See git-enhance(1).

usage() {
  echo "usage: git enhance [--force]"
}

force=false
while (( $# > 0 )); do
  case "$1" in
    -f|--force) force=true ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
  esac
  shift
done

dotfiles="${GIT_ENHANCE_DOTFILES:-$HOME/repos/dotfiles}"
skills_root="${GIT_ENHANCE_SKILLS:-$HOME/.vibes/skills/repos}"
repos_root="${GIT_ENHANCE_REPOS:-$HOME/repos}"

marker="# Generated by git-enhance. Changes will be overwritten."

if [[ "$(git rev-parse --is-bare-repository)" == true ]]; then
  echo "git enhance: bare repository, nothing to do." >&2
  exit 0
fi
toplevel="$(git rev-parse --show-toplevel)"

# The repo name is the first path component under `$repos_root` of the main
# checkout. Use the common git dir rather than the top level so linked
# worktrees resolve to their repo wherever they live.
common="$(git rev-parse --path-format=absolute --git-common-dir)"
main="$(dirname "$common")"
name=""
if [[ "$main" == "$repos_root"/* ]]; then
  name="${main#"$repos_root"/}"
  name="${name%%/*}"
fi

failed=false

# Prints a path relative to the top level for messages.
show() {
  echo "${1#"$toplevel"/}"
}

warn() {
  echo "git enhance: $*" >&2
}

# Succeeds if the repo tracks `$1`.
is_tracked() {
  git -C "$toplevel" ls-files --error-unmatch -- "$1" >/dev/null 2>&1
}

# Replaces the file `$1` with the content `$2` and a trailing newline.
write_atomic() {
  local target="$1" content="$2" tmp
  mkdir -p "$(dirname "$target")"
  tmp="$(mktemp "$target.XXXXXX")"
  printf '%s\n' "$content" > "$tmp"
  mv "$tmp" "$target"
}

# Brings the file `$1` in line with the content `$3`, or removes it when `$3`
# is empty. `$2` is a command that succeeds when the existing file was
# written by git enhance.
#
# Runs with `set -e` in effect, so unexpected failures abort the command.
reconcile() {
  local target="$1" owned_check="$2" desired="$3"
  if is_tracked "$target"; then
    if [[ -n "$desired" ]]; then
      warn "$(show "$target") is tracked by the repo, leaving it alone."
    fi
    return
  fi
  local owned=false
  if [[ -e "$target" ]] && "$owned_check" "$target"; then
    owned=true
  fi
  if [[ -z "$desired" ]]; then
    if $owned; then
      rm -f "$target"
      echo "Removed $(show "$target")"
    fi
    return
  fi
  if [[ -e "$target" ]] && ! $owned; then
    if ! $force; then
      warn "$(show "$target") was not written by git enhance." \
        "Move its contents into git enhance or rerun with --force to" \
        "replace it."
      failed=true
      return
    fi
    warn "Replacing $(show "$target")."
  fi
  if [[ -f "$target" ]] && [[ "$(cat "$target")" == "$desired" ]]; then
    return
  fi
  write_atomic "$target" "$desired"
  echo "Wrote $(show "$target")"
}

### .envrc for a dev shell from the dotfiles flake.

envrc_owned() {
  [[ "$(head -n 1 "$1")" == "$marker" ]]
}

envrc="$toplevel/.envrc"
envrc_content=""
if [[ -n "$name" && -f "$dotfiles/dev-shells/$name.nix" ]]; then
  # `source_up_if_exists` keeps an `.envrc` above the checkout working, such
  # as the gclient root for dart-sdk.
  envrc_content="$(printf '%s\n' \
    "$marker" \
    "source_up_if_exists" \
    "use flake $dotfiles#$name")"
fi
reconcile "$envrc" envrc_owned "$envrc_content"
if [[ -n "$envrc_content" && -f "$envrc" ]] && envrc_owned "$envrc"; then
  if command -v direnv >/dev/null; then
    direnv allow "$envrc"
  else
    warn "direnv is not installed, $(show "$envrc") will not load."
  fi
fi

### .agents/skills/ hardlinks and .agents/skills.json cleanup.

exclude_begin="# begin git-enhance"
exclude_end="# end git-enhance"

# Rewrites the git-enhance managed block in `.git/info/exclude` (shared across
# linked worktrees) to ignore `$@`, or drops the block when `$@` is empty.
update_exclude() {
  local exclude_file existing="" block="" desired="" line
  exclude_file="$(git -C "$toplevel" rev-parse --path-format=absolute \
    --git-path info/exclude)"
  if [[ -f "$exclude_file" ]]; then
    existing="$(sed "/^$exclude_begin\$/,/^$exclude_end\$/d" \
      "$exclude_file")"
  fi
  if (( $# > 0 )); then
    block="$exclude_begin"
    for line in "$@"; do
      block+=$'\n'"$line"
    done
    block+=$'\n'"$exclude_end"
  fi
  if [[ -n "$existing" && -n "$block" ]]; then
    desired="$existing"$'\n'"$block"
  elif [[ -n "$existing" ]]; then
    desired="$existing"
  else
    desired="$block"
  fi
  if [[ ! -f "$exclude_file" && -z "$desired" ]]; then
    return
  fi
  if [[ -f "$exclude_file" ]] && [[ "$(cat "$exclude_file")" == "$desired" ]]; then
    return
  fi
  if [[ -z "$desired" ]]; then
    rm -f "$exclude_file"
  else
    write_atomic "$exclude_file" "$desired"
  fi
}

# Succeeds if `$1` and `$2` are regular files sharing the same inode.
same_inode() {
  [[ -f "$1" && ! -L "$1" && -f "$2" && ! -L "$2" && "$1" -ef "$2" ]]
}

# Succeeds if `$1` is a skill directory containing `SKILL.md` hardlinked to a
# file anywhere under `$skills_root`, or an empty directory left by an
# interrupted run.
skill_dir_owned() {
  local dir="$1" src_md
  [[ -d "$dir" && ! -L "$dir" ]] || return 1
  if [[ -z "$(find "$dir" -mindepth 1 -print -quit)" ]]; then
    return 0
  fi
  [[ -f "$dir/SKILL.md" && ! -L "$dir/SKILL.md" ]] || return 1
  for src_md in "$skills_root"/*/*/SKILL.md; do
    [[ -f "$src_md" ]] || continue
    if [[ "$dir/SKILL.md" -ef "$src_md" ]]; then
      return 0
    fi
  done
  return 1
}

# Hardlinks every regular file under `$1` into `$2`, removing stale files and
# directories under `$2`. Assumes `$2` is untracked and owned (or new).
sync_skill_dir() {
  local src_dir="$1" dst_dir="$2" changed=false existed=false
  local rel src_entry dst_entry
  [[ -e "$dst_dir" ]] && existed=true
  if [[ ! -d "$dst_dir" || -L "$dst_dir" ]]; then
    rm -rf "$dst_dir"
    mkdir -p "$dst_dir"
    changed=true
  fi

  # Remove entries in `$dst_dir` not matching `$src_dir`.
  while IFS= read -r -d '' dst_entry; do
    rel="${dst_entry#"$dst_dir"/}"
    src_entry="$src_dir/$rel"
    if [[ -L "$dst_entry" ]]; then
      rm -rf "$dst_entry"
      changed=true
    elif [[ -d "$dst_entry" ]]; then
      if [[ ! -d "$src_entry" || -L "$src_entry" ]]; then
        rm -rf "$dst_entry"
        changed=true
      fi
    elif [[ ! -f "$src_entry" || -L "$src_entry" ]]; then
      rm -f "$dst_entry"
      changed=true
    fi
  done < <(find "$dst_dir" -mindepth 1 -depth -print0)

  # Create directories and hardlink regular files from `$src_dir`.
  while IFS= read -r -d '' src_entry; do
    rel="${src_entry#"$src_dir"/}"
    dst_entry="$dst_dir/$rel"
    if [[ -L "$src_entry" ]]; then
      warn "skipping symlink in skill source: $src_entry"
      continue
    elif [[ -d "$src_entry" ]]; then
      if [[ ! -d "$dst_entry" ]]; then
        mkdir -p "$dst_entry"
        changed=true
      fi
    elif [[ -f "$src_entry" ]]; then
      if ! same_inode "$src_entry" "$dst_entry"; then
        mkdir -p "$(dirname "$dst_entry")"
        ln -f "$src_entry" "$dst_entry"
        changed=true
      fi
    fi
  done < <(find "$src_dir" -mindepth 1 -print0)

  if $changed; then
    if $existed; then
      echo "Updated $(show "$dst_dir")"
    else
      echo "Wrote $(show "$dst_dir")"
    fi
  fi
}

# Drops any legacy `.vibes/skills/repos` entries from `.agents/skills.json`,
# leaving unrelated entries intact.
# shellcheck disable=SC2016 # `$root` is a jq variable.
skills_cleanup_filter='
  def ours: (.path? // null) | type == "string" and startswith($root);
  if type != "object" or ((.entries // []) | type) != "array" then
    error("expected an object with an \"entries\" array")
  else . end
  | ((.entries // []) | map(select(ours | not))) as $entries
  | if (.entries // []) == $entries then . else .entries = $entries end
'

clean_legacy_skills_json() {
  local target="$toplevel/.agents/skills.json" before after
  [[ -e "$target" ]] || return 0
  is_tracked "$target" && return 0
  if ! before="$(jq -S . "$target" 2>/dev/null)" ||
      ! after="$(jq --arg root "$skills_root/" \
        "$skills_cleanup_filter" "$target" 2>/dev/null)"; then
    warn "$(show "$target") is not a valid skills file, leaving it alone."
    return 0
  fi
  if [[ "$(jq -S . <<<"$after")" == "$before" ]]; then
    return 0
  fi
  if [[ "$(jq -c . <<<"$after")" == '{"entries":[]}' ]]; then
    rm -f "$target"
    rmdir "$(dirname "$target")" 2>/dev/null || true
    echo "Removed $(show "$target")"
    return 0
  fi
  write_atomic "$target" "$after"
  echo "Updated $(show "$target")"
}

# Succeeds if the repo tracks anything at or under `$1`.
has_tracked_files() {
  [[ -n "$(git -C "$toplevel" ls-files -- "$1")" ]]
}

update_skills() {
  local skills_dir="$toplevel/.agents/skills"
  local src_repo_dir="" skill_src skill_name dst_skill
  local -a wanted=() excludes=()

  if [[ -n "$name" && -d "$skills_root/$name" ]]; then
    src_repo_dir="$skills_root/$name"
    for skill_src in "$src_repo_dir"/*; do
      [[ -d "$skill_src" && -f "$skill_src/SKILL.md" ]] || continue
      skill_name="$(basename "$skill_src")"
      wanted+=("$skill_name")
      excludes+=("/.agents/skills/$skill_name/")
    done
  fi

  # Remove stale skill directories previously linked from `$skills_root`.
  if [[ -d "$skills_dir" ]]; then
    for dst_skill in "$skills_dir"/*; do
      [[ -e "$dst_skill" || -L "$dst_skill" ]] || continue
      skill_name="$(basename "$dst_skill")"
      local keep=false w
      if (( ${#wanted[@]} > 0 )); then
        for w in "${wanted[@]}"; do
          if [[ "$w" == "$skill_name" ]]; then
            keep=true
            break
          fi
        done
      fi
      if ! $keep && ! has_tracked_files "$dst_skill" && \
          skill_dir_owned "$dst_skill"; then
        rm -rf "$dst_skill"
        echo "Removed $(show "$dst_skill")"
      fi
    done
  fi

  # Sync wanted skill directories via hardlinks.
  if [[ -n "$src_repo_dir" ]] && (( ${#wanted[@]} > 0 )); then
    for skill_name in "${wanted[@]}"; do
      skill_src="$src_repo_dir/$skill_name"
      dst_skill="$skills_dir/$skill_name"
      if has_tracked_files "$dst_skill"; then
        warn "$(show "$dst_skill") is tracked by the repo, leaving it alone."
        continue
      fi
      if [[ -e "$dst_skill" || -L "$dst_skill" ]] && \
          ! skill_dir_owned "$dst_skill"; then
        if ! $force; then
          warn "$(show "$dst_skill") was not written by git enhance." \
            "Move its contents into git enhance or rerun with --force to" \
            "replace it."
          failed=true
          continue
        fi
        warn "Replacing $(show "$dst_skill")."
        rm -rf "$dst_skill"
      fi
      sync_skill_dir "$skill_src" "$dst_skill"
    done
  fi

  if [[ -d "$skills_dir" ]]; then
    rmdir "$skills_dir" 2>/dev/null || true
    rmdir "$(dirname "$skills_dir")" 2>/dev/null || true
  fi

  if (( ${#excludes[@]} > 0 )); then
    update_exclude "${excludes[@]}"
  else
    update_exclude
  fi
  clean_legacy_skills_json
}
update_skills

if $failed; then
  exit 1
fi
